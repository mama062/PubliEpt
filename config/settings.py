import os
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent


def lire_env(nom, defaut=""):
    """Lecture simple d'une variable d'environnement, avec repli sur le
    fichier .env s'il existe (évite une dépendance supplémentaire)."""
    if nom in os.environ:
        return os.environ[nom]
    fichier = BASE_DIR / ".env"
    if fichier.exists():
        for ligne in fichier.read_text(encoding="utf-8").splitlines():
            ligne = ligne.strip()
            if not ligne or ligne.startswith("#") or "=" not in ligne:
                continue
            cle, _, valeur = ligne.partition("=")
            if cle.strip() == nom:
                return valeur.strip().strip('"').strip("'")
    return defaut


